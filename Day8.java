public class Main {
	public static void main(String[] args){
		
		// Membuat Variabel Tanpa Isi (Deklarasi Variabel)
		    int umur = 18;
		
		// Memberikan Nilai Pertama (Inisialisasi Variabel)
		    umur = 18;
		    System.out.println("Umur Awal: " + umur);
		
		// Deklarasi Dan Inisialisasi Dalam Satu Baris
		    String nama = "Herdi Bonggatasik";
		    System.out.println("Nama: " + nama);
		
		// Mengubah Nilai Yang Sudah Ada (Update Variabel)
		    umur = 20;
		    System.out.println("Umur Setelah Update: " + umur);
	}
}
