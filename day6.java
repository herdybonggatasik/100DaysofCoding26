public class Main {
    public static void main(String[] args) {
        // Tipe data karakter (char)
        char jenisKelamin = 'L';
        char simbol = '$';
        
        // Tipe data boolean (boolean)
        boolean lulusTidak = true;
        boolean hujanTidak = false;
        
        // Tampilan Hasil
        System.out.println("--- Tipe Data Char ---");
        System.out.println("jenisKelamin = " +jenisKelamin);
        System.out.println("simbol = " +simbol);
        
        System.out.println("--- Tipe Data Boolean---");
        System.out.println("lulus tidak = " +lulusTidak);
        System.out.println("hujan tidak = " +hujanTidak);
        
    }
}
